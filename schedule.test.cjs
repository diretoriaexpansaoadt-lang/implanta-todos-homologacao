const assert = require('node:assert/strict');
const s = require('./schedule');
const state = { units: [{ id: 'a', active: true, plannedOpeningDate: '2026-10-30', documentLeadDays: 5 }, { id: 'b', active: true, plannedOpeningDate: '2026-12-01', documentLeadDays: 10 }, { id: 'legacy' }], items: [{ id: 'i', item: 'Obra', prazo: '15 DIAS' }, { id: 'j', prazo: 'A DEFINIR' }], checklist: {}, documents: { 'a::doc-01': { prazo: '20 DIAS' } } };
s.apply(state, '2026-10-12');
assert.equal(state.checklist['a::i'].vencimento, '2026-10-15');
assert.equal(state.checklist['b::i'].vencimento, '2026-11-16');
assert.equal(state.documents['a::doc-01'].vencimento, '2026-10-10');
assert.equal(state.documents['a::doc-02'].vencimento, '2026-10-25');
assert.equal(state.units[0].adjustedOpeningDate, '2026-11-01');
assert.equal(state.checklist['legacy::i'], undefined);
assert.equal(s.distance('2026-10-15', '2026-10-12'), 3);
assert.equal(s.forecast(state, state.units[0], '2026-10-12').missing, 1);
// Repeated checks never compound the delay or move original deadlines.
s.apply(state, '2026-10-12');
assert.equal(state.units[0].adjustedOpeningDate, '2026-11-01');
state.documents['a::doc-01'].status = 'Concluido';
state.documents['a::doc-01'].approvedAt = '2026-10-12T12:00:00Z';
s.apply(state, '2026-10-12');
state.checklist['a::i'].done = true;
s.apply(state, '2026-10-18');
assert.equal(state.units[0].adjustedOpeningDate, '2026-11-02');
s.apply(state, '2026-10-20');
assert.equal(state.units[0].adjustedOpeningDate, '2026-11-02');
assert.equal(state.checklist['a::i'].vencimento, '2026-10-15');
assert.equal(s.validDate('2026-02-30'), false);
assert.equal(s.lead('-3 DIAS'), null);
assert.equal(s.lead('15 DIAS'), 15);
assert.equal(s.shift('2028-03-01', -1), '2028-02-29');
assert.equal(s.lead('999999999999'), null);
console.log('PASS: unit isolation, item/document offsets, 3-day reminder, late completion, non-compounding forecast, unknown deadlines, invalid dates, leap year');
